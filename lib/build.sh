#!/data/data/com.termux/files/usr/bin/bash
#
# Tanoshi for Termux — build routine.
#
# Builds the Tanoshi server (and optionally the source extensions) from a
# specific upstream git ref, applying the Android patches this package carries.
# Used by `install.sh --from-source` and by `update.sh`.
#
# Usage:
#   bash lib/build.sh --ref <tag-or-branch> --install-to <pkg-dir>
#   bash lib/build.sh --extensions-only --install-to <pkg-dir>
#                      [--extensions] [--extensions-only]
#
# Prints machine-readable markers on completion:
#   BUILT_VERSION=<version>     server version (Cargo.toml of crate `tanoshi`)
#   BUILT_LIB_VERSION=<version> tanoshi-lib version (plugins must match this)

set -euo pipefail

# Resolve symlinks so the script works even when invoked through a link.
_SELF="${BASH_SOURCE[0]:-$0}"
while [ -L "$_SELF" ]; do
  _link="$(readlink "$_SELF")"
  case "$_link" in
    /*) _SELF="$_link" ;;
    *)  _SELF="$(dirname "$_SELF")/$_link" ;;
  esac
done
SCRIPT_DIR="$(cd "$(dirname "$_SELF")" && pwd -P)"
PKG_DIR="$(cd "$SCRIPT_DIR/.." && pwd -P)"
# shellcheck source=common.sh
. "$SCRIPT_DIR/common.sh"

REF=""
INSTALL_TO="$PKG_DIR"
BUILD_EXTENSIONS=0
EXT_ONLY=0

while [ $# -gt 0 ]; do
  case "$1" in
    --ref) REF="${2:?--ref needs a value}"; shift 2 ;;
    --install-to) INSTALL_TO="${2:?--install-to needs a value}"; shift 2 ;;
    --extensions) BUILD_EXTENSIONS=1; shift ;;
    --extensions-only) BUILD_EXTENSIONS=1; EXT_ONLY=1; shift ;;
    -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "build.sh: unknown option $1" ;;
  esac
done

[ -n "$REF" ] || [ "$EXT_ONLY" = "1" ] || die "build.sh: --ref is required"
[ -d "$INSTALL_TO" ] || die "build.sh: --install-to path does not exist: $INSTALL_TO"

: "${WORK_DIR:=$HOME/.tanoshi-build}"
mkdir -p "$WORK_DIR"
CARGO_HOME_DIR="$WORK_DIR/cargo-home"
NATIVE_TARGET="$WORK_DIR/native-target"
WASM_TARGET="$WORK_DIR/wasm-target"
SRC_DIR="$WORK_DIR/tanoshi-src"

export PATH="$HOME/.cargo/bin:$HOME/.local/bin:$PATH"

# ---------------------------------------------------------------------------
# Cargo configuration: patch compress-tools with the vendored Android build.
# ---------------------------------------------------------------------------
setup_cargo_home() {
  mkdir -p "$CARGO_HOME_DIR"
  local vendored="$PKG_DIR/vendor/compress-tools-0.16.1"
  [ -d "$vendored" ] || die "missing vendored crate: $vendored"
  cat >"$CARGO_HOME_DIR/config.toml" <<EOF
# Generated by tanoshi build.sh — patches compress-tools for Termux/Android.
[patch.crates-io]
compress-tools = { path = "$vendored" }
EOF
  export CARGO_HOME="$CARGO_HOME_DIR"
}

# ---------------------------------------------------------------------------
# Source checkout at the requested ref.
# ---------------------------------------------------------------------------
checkout_source() {
  step "Fetching Tanoshi $REF"
  if [ ! -d "$SRC_DIR/.git" ]; then
    rm -rf "$SRC_DIR"
    git clone --depth 1 "https://github.com/$UPSTREAM_REPO.git" "$SRC_DIR" --quiet \
      || die "failed to clone $UPSTREAM_REPO"
  fi

  # Always start from a pristine tree so the patches apply to clean sources.
  git -C "$SRC_DIR" checkout --force --quiet -- . 2>/dev/null || true
  git -C "$SRC_DIR" clean -fdq 2>/dev/null || true

  git -C "$SRC_DIR" fetch --depth 1 origin "$REF" --quiet 2>/dev/null \
    || git -C "$SRC_DIR" fetch --depth 1 origin "v$REF" --quiet 2>/dev/null \
    || die "cannot fetch ref '$REF' (also tried 'v$REF') from $UPSTREAM_REPO"
  git -C "$SRC_DIR" checkout --force --detach FETCH_HEAD --quiet 2>/dev/null \
    || die "cannot check out '$REF'"
  git -C "$SRC_DIR" clean -fdq 2>/dev/null || true

  [ -d "$SRC_DIR/crates/tanoshi" ] || die "checkout failed: $SRC_DIR"
  ok "source at $(git -C "$SRC_DIR" rev-parse --short HEAD 2>/dev/null || echo '?') ($REF)"
}

# ---------------------------------------------------------------------------
# Android patches.
# ---------------------------------------------------------------------------
apply_android_patches() {
  step "Applying Android patches"
  local patch_file="$PKG_DIR/patches/tanoshi-android.patch"
  [ -f "$patch_file" ] || die "missing $patch_file"

  if git -C "$SRC_DIR" apply --check --whitespace=nowarn "$patch_file" 2>/dev/null; then
    git -C "$SRC_DIR" apply --whitespace=nowarn "$patch_file"
    ok "patch applied"
  elif git -C "$SRC_DIR" apply --3way --whitespace=nowarn "$patch_file" 2>/dev/null; then
    ok "patch applied (3-way merge)"
  else
    warn "the Android patch does not apply cleanly to $REF."
    warn "Upstream likely changed the files it touches. Review:"
    warn "  $patch_file"
    die "cannot continue: the build would not work on Termux without these patches"
  fi

  # Two files are added by the patch set and are not produced by `git diff`.
  cp "$PKG_DIR/patches/http.rs.new" "$SRC_DIR/crates/tanoshi/src/infrastructure/http.rs"
  cp "$PKG_DIR/patches/extension-build.rs.new" "$SRC_DIR/crates/tanoshi-vm/src/extension/build.rs"
  # Register the new modules/patch anchors that the diff already handled; the
  # copies above only provide file contents.
  ok "helper sources in place"
}

# ---------------------------------------------------------------------------
# Build the wasm web UI (embedded into the server binary).
# ---------------------------------------------------------------------------
build_web() {
  step "Building web UI (wasm)"
  ( cd "$SRC_DIR/crates/tanoshi-web" \
    && CARGO_TARGET_DIR="$WASM_TARGET" trunk build --release 2>&1 | tail -4 )
  [ -f "$SRC_DIR/crates/tanoshi-web/dist/index.html" ] || die "web build produced no dist/index.html"
  ok "web UI built"
}

# ---------------------------------------------------------------------------
# Build the server binary.
# ---------------------------------------------------------------------------
build_server() {
  step "Building tanoshi server (this takes a while)"
  ( cd "$SRC_DIR" \
    && CARGO_TARGET_DIR="$NATIVE_TARGET" \
       RUSTFLAGS="-Clink-arg=-Wl,--allow-multiple-definition" \
       cargo build -p tanoshi --release 2>&1 | tail -4 )
  [ -x "$NATIVE_TARGET/release/tanoshi" ] || die "server build produced no binary"
  ok "server built"
}

install_binary() {
  step "Installing binary"
  mkdir -p "$INSTALL_TO/bin"
  # Copy to a temp name first so a running server keeps its inode.
  cp "$NATIVE_TARGET/release/tanoshi" "$INSTALL_TO/bin/.tanoshi.new"
  chmod 700 "$INSTALL_TO/bin/.tanoshi.new"
  mv -f "$INSTALL_TO/bin/.tanoshi.new" "$INSTALL_TO/bin/tanoshi"
  ok "$INSTALL_TO/bin/tanoshi"
}

# ---------------------------------------------------------------------------
# Extensions: build every plugin from the source workspace.
# ---------------------------------------------------------------------------
build_extensions() {
  step "Building source extensions"
  local ext_src="$WORK_DIR/extensions-src"
  local ext_target="$WORK_DIR/extensions-target"

  if [ -d "$ext_src/.git" ]; then
    git -C "$ext_src" fetch --depth 1 origin --quiet 2>/dev/null || true
    git -C "$ext_src" reset --hard origin/HEAD --quiet 2>/dev/null \
      || git -C "$ext_src" reset --hard --quiet 2>/dev/null || true
    git -C "$ext_src" clean -fd --quiet 2>/dev/null || true
  else
    rm -rf "$ext_src"
    git clone --depth 1 "https://github.com/$EXTENSIONS_REPO.git" "$ext_src" --quiet
  fi
  [ -f "$ext_src/Cargo.toml" ] || die "extension workspace checkout failed (no Cargo.toml)"

  # Shared helpers the ported extensions rely on.
  local netpatch="$PKG_DIR/patches/networking-helpers.patch"
  if git -C "$ext_src" apply --check --whitespace=nowarn "$netpatch" 2>/dev/null; then
    git -C "$ext_src" apply --whitespace=nowarn "$netpatch"
    ok "networking helpers applied"
  elif git -C "$ext_src" diff --quiet -- common/networking 2>/dev/null; then
    warn "networking helpers patch did not apply; ported extensions may fail to build"
  else
    ok "networking helpers already present"
  fi

  # Copy the ported extensions into the workspace.
  local port
  for port in "${PORTED_PLUGINS[@]}"; do
    [ -d "$PKG_DIR/extensions/$port" ] || continue
    rm -rf "$ext_src/extensions/$port"
    cp -r "$PKG_DIR/extensions/$port" "$ext_src/extensions/$port"
  done

  # Only build what the package wants to ship.
  local -a pkg_args=()
  local name
  for name in "${PLUGIN_NAMES[@]}"; do
    if [ -d "$ext_src/extensions/$name" ]; then
      pkg_args+=(-p "$name")
    else
      warn "extension '$name' is not in the upstream workspace; skipping"
    fi
  done
  [ "${#pkg_args[@]}" -gt 0 ] || die "no extensions to build"

  ( cd "$ext_src" \
    && CARGO_TARGET_DIR="$ext_target" cargo build --release "${pkg_args[@]}" 2>&1 | tail -4 )

  mkdir -p "$INSTALL_TO/plugins"
  local built=0
  for name in "${PLUGIN_NAMES[@]}"; do
    local so="$ext_target/release/lib${name}.so"
    if [ -f "$so" ]; then
      cp "$so" "$INSTALL_TO/plugins/${name}.so"
      built=$((built + 1))
    else
      warn "no library produced for $name"
    fi
  done
  [ "$built" -gt 0 ] || die "no extension libraries were produced"
  ok "installed $built extension(s)"
}

# ---------------------------------------------------------------------------
# Version reporting
# ---------------------------------------------------------------------------
report_versions() {
  local ver libver
  ver="$(grep -m1 '^version' "$SRC_DIR/crates/tanoshi/Cargo.toml" | sed 's/.*"\(.*\)".*/\1/')"
  libver="$(grep -m1 '^version' "$SRC_DIR/crates/tanoshi-lib/Cargo.toml" | sed 's/.*"\(.*\)".*/\1/')"
  printf 'BUILT_VERSION=%s\n' "${ver:-unknown}"
  printf 'BUILT_LIB_VERSION=%s\n' "${libver:-unknown}"
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

setup_cargo_home

if [ "$EXT_ONLY" = "1" ]; then
  build_extensions
  exit 0
fi

checkout_source
apply_android_patches
build_web
build_server
install_binary
if [ "$BUILD_EXTENSIONS" = "1" ]; then
  build_extensions
fi
report_versions
